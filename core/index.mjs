#!/usr/bin/env node
// Regenerates the index at the end of ENTRY.md: one line per file, pipe-delimited, from each file's first heading or description.
//   node core/index.mjs
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const walk = (dir, base = dir, out = []) => { for (const n of fs.readdirSync(dir).sort()) { if (n.startsWith('.') || n === 'tweaks' || n === 'examples' || n === 'node_modules') continue; if (path.relative(base, path.join(dir, n)).match(/^library\/(domains|areas)$/)) continue; const p = path.join(dir, n); if (fs.statSync(p).isDirectory()) walk(p, base, out); else if (/\.(md|mjs|yml)$/.test(n)) out.push(path.relative(base, p)); } return out; };
const first = (p) => {
  const s = fs.readFileSync(path.join(root, p), 'utf8');
  const fm = s.match(/^---\n([\s\S]*?)\n---/); if (fm) { const d = fm[1].match(/^description:\s*(.+)$/m); if (d) return d[1].trim(); const t = fm[1].match(/^(template|role):\s*(.+)$/m); const sc = fm[1].match(/^(scope|runs as):\s*(.+)$/m); if (t) return `${t[1]} ${t[2].trim()}` + (sc ? ` | ${sc[1]} ${sc[2].trim()}` : ""); }
  const c = s.match(/^\/\/\s*(.+)$/m); if (p.endsWith('.mjs') && c) return c[1].trim();
  const h = s.match(/^#\s+(.+)$/m); const sub = s.split('\n').find(l => l.trim() && !l.startsWith('#') && !l.startsWith('---') && !l.startsWith('<!--'));
  return (h ? h[1] : '') + (sub ? ' | ' + sub.trim().slice(0, 110) : '');
};
const lines = walk(root).filter(f => f !== 'ENTRY.md' && f !== 'LICENSE').map(f => `${f} | ${first(f).replace(/\s+/g, ' ').slice(0, 140)}`);
const entry = path.join(root, 'ENTRY.md');
const s = fs.readFileSync(entry, 'utf8');
const out = s.replace(/<!-- index:start -->[\s\S]*<!-- index:end -->/, '<!-- index:start -->\n```\n' + lines.join('\n') + '\n```\n<!-- index:end -->');
fs.writeFileSync(entry, out);
console.log(`index: ${lines.length} files, ${Buffer.byteLength(out)} bytes in ENTRY.md`);

// The library: its own index (library/index.md), and a shape check of every file against library/template.md.
const lib = path.join(root, 'library');
if (fs.existsSync(lib)) {
  const SECTIONS = ['Questions worth asking', 'Usual shape', 'Choices and trade-offs', 'Watch out', 'Go deeper', 'Related'];
  const files = walk(lib, lib).filter(f => /^(domains|areas)\//.test(f) && f.endsWith('.md'));
  const rows = {}, problems = [];
  for (const f of files) {
    const s = fs.readFileSync(path.join(lib, f), 'utf8');
    const fm = (s.match(/^---\n([\s\S]*?)\n---/) || [, ''])[1];
    const key = (k) => (fm.match(new RegExp('^' + k + ':\\s*(.+)$', 'm')) || [, ''])[1].trim();
    const need = ['kind', 'shelf', 'name', 'fits when', 'related', 'checked'].concat(f.startsWith('domains/') ? ['group'] : []);
    for (const k of need) if (!key(k)) problems.push(`${f}: no "${k}:"`);
    const heads = [...s.matchAll(/^## (.+)$/gm)].map(m => m[1].trim());
    const odd = heads.filter(h => !SECTIONS.includes(h)); if (odd.length) problems.push(`${f}: sections not in the template: ${odd.join(', ')}`);
    const order = heads.filter(h => SECTIONS.includes(h)); if (order.join() !== SECTIONS.filter(h => order.includes(h)).join()) problems.push(`${f}: sections out of order`);
    for (const h of ['Go deeper', 'Related']) if (!heads.includes(h)) problems.push(`${f}: no "## ${h}"`);
    if (!/^## Go deeper[\s\S]*?\]\(https?:\/\//m.test(s)) problems.push(`${f}: Go deeper has no link`);
    for (const r of key('related').split(',').map(x => x.trim()).filter(Boolean)) if (!fs.existsSync(path.join(lib, r))) problems.push(`${f}: related ${r} does not exist`);
    for (const m of s.matchAll(/^- `([^`]+\.md)`/gm)) if (!fs.existsSync(path.join(lib, m[1]))) problems.push(`${f}: Related ${m[1]} does not exist`);
    const lines = s.split('\n').length; if (lines > 140) problems.push(`${f}: ${lines} lines (one to two pages)`);
    const shelf = f.startsWith('domains/') ? 'Domains · ' + (key('group') === 'sector' ? 'sectors' : 'models') : 'Area knowledge · ' + f.split('/')[1].replace(/-/g, ' ');
    (rows[shelf] = rows[shelf] || []).push(`${f} | ${key('name')} | ${key('fits when')}`);
  }
  const order = (k) => ['Domains · models', 'Domains · sectors', 'Area knowledge · platforms', 'Area knowledge · design systems', 'Area knowledge · patterns', 'Area knowledge · parts', 'Area knowledge · practices'].indexOf(k);
  const body = Object.keys(rows).sort((a, b) => order(a) - order(b)).map(k => `## ${k}\n\n` + rows[k].join('\n')).join('\n\n');
  fs.writeFileSync(path.join(lib, 'index.md'), `# Library index\n\nGenerated by \`node core/index.mjs\`; do not edit by hand. One line per file: path | name | fits when. Read this, then only the files that match the project (\`library/use-library.md\`).\n\n${body}\n`);
  console.log(`library: ${files.length} files in library/index.md` + (problems.length ? `, ${problems.length} problem(s):\n  ` + problems.join('\n  ') : ', all in shape'));
}
